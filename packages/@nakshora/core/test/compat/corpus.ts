export function dynamicCorpus(): string[] {
  const out = new Set<string>(ARBITRARY);
  for (const v of VARIANTS) for (const b of BASES) out.add(`${v}:${b}`);
  for (const b of BASES2)
    for (const v of [
      'hover',
      'md',
      'dark',
      'group-hover',
      'before',
      '*',
      'print',
      '@md',
      'supports-[display:grid]',
    ])
      out.add(`${v}:${b}`);
  for (const s of STACKS)
    for (const b of ['p-1', 'bg-red-500/50', 'space-x-4']) out.add(`${s}:${b}`);
  return [...out];
}

export function mediaStackCorpus(): string[] {
  const out = new Set<string>();
  for (const s of MEDIA_STACKS)
    for (const b of ['p-1', 'bg-red-500/50', 'space-x-4', 'flex']) out.add(`${s}:${b}`);
  return [...out];
}
